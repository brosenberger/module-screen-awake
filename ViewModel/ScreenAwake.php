declare(strict_types=1);

namespace BroCode\ScreenAwake\ViewModel;

use Magento\Catalog\Api\Data\ProductInterface;
use Magento\Framework\App\Config\ScopeConfigInterface;
use Magento\Framework\View\Element\Block\ArgumentInterface;
use Magento\Store\Model\ScopeInterface;

/**
 * Decides where the "Keep screen on" button renders: the store switch everywhere,
 * plus the per-product attribute on product pages.
 */
class ScreenAwake implements ArgumentInterface
{
    public const XML_PATH_ENABLED = 'catalog/screen_awake/enabled';
    public const PRODUCT_ATTRIBUTE = 'screen_awake_button';

    /**
     * @var ScopeConfigInterface
     */
    private $scopeConfig;

    public function __construct(ScopeConfigInterface $scopeConfig)
    {
        $this->scopeConfig = $scopeConfig;
    }

    public function isEnabled(): bool
    {
        return $this->scopeConfig->isSetFlag(self::XML_PATH_ENABLED, ScopeInterface::SCOPE_STORE);
    }

    public function isEnabledForProduct(?ProductInterface $product): bool
    {
        if ($product === null || !$this->isEnabled()) {
            return false;
        }

        return (bool) $product->getData(self::PRODUCT_ATTRIBUTE);
    }
}
